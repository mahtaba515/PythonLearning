# Escape Sequences
# • Escape sequences are used to include special characters in strings.
# • Common escape sequences:
#
#   • \n : Newline
#   • \t : Tab
#   • \\ : Backslash
#   • \" : Double quote
#   • \' : Single quote
#
# • Example:

# print("Hello\nWorld!")
# print("This is a tab\tcharacter.")




print("Hello! \nKaise ho") # print new line using \n

print("Hello! \tKaise ho") # printing tab

print("Hello! \\Kaise ho") # print backslash

print("Hello! \"Kaise ho") # print double qoute

print("Hello! \'Kaise ho") # print single qoute

